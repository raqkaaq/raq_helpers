"""Shared conventions for code generators."""

from datetime import datetime, timezone
from importlib.metadata import PackageNotFoundError, version


class GeneratorBase:
    @staticmethod
    def generator_version() -> str:
        """Return the installed raq-helpers version used for generation."""
        try:
            return version("raq-helpers")
        except PackageNotFoundError:
            return "unknown"

    def generated_file_metadata(self) -> str:
        """Return importable provenance for generated Python modules."""
        return f"__generator_version__ = {self.generator_version()!r}\n"

    def generated_file_header(self) -> str:
        """Return a Python comment header; subclasses may supply their own message."""
        generator = f"{type(self).__module__}.{type(self).__qualname__}"
        generator_version = self.generator_version()
        return (
            f"# This file is automatically generated by {generator}.\n"
            f"# raq-helpers version: {generator_version}\n"
            f"# Generated at: {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n"
            "# Manual changes will be overwritten the next time it is generated.\n"
            "# To change this output, update the source schema or generator configuration.\n"
        )
